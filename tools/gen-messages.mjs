/*
 * gen-messages.mjs
 *
 * Emits docs/text-messages/IP_messages_en.sql - a ready to run script that creates every
 * Text Message the picker looks up, in English, flagged for JavaScript.
 *
 * The IP.CATEGORY.* lines are generated from src/js/icons.js rather than typed out, so the
 * list cannot drift from the catalog when Font APEX adds or drops a category.
 *
 * Developers run it once per language with p_language changed and the texts translated.
 * Creating no messages at all is fine: every string falls back to the English built into
 * the plug-in.
 *
 *   node tools/gen-messages.mjs        (or: npm run messages)
 */

import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const ROOT   = join( dirname( fileURLToPath( import.meta.url ) ), '..' );
const TARGET = join( ROOT, 'docs', 'text-messages', 'IP_messages_en.sql' );

// Keep in step with the msg() calls in src/js/iconpicker.js
const UI_MESSAGES = [
    [ 'IP.ALL',              'All',              'Label of the "All" category tab' ],
    [ 'IP.CATEGORY_HEADING', '%0 Icons',         'Heading above a category, %0 is the category name' ],
    [ 'IP.RESULTS',          '%0 Results',       'Search result count, %0 is the number of hits' ],
    [ 'IP.NO_RESULTS',       'No results',       'Shown when a search matches nothing' ],
    [ 'IP.SEARCH',           'Search',           'Hidden label on the search field' ],
    [ 'IP.CLOSE',            'Close',            'Hidden label on the dialog close button' ],
    [ 'IP.ICON_SIZE',        'Icon size',        'Group label on the Small / Large toggle' ],
    [ 'IP.CATEGORIES',       'Icon categories',  'Group label on the category tab row' ]
];

// ---------------------------------------------------------------------------

function categoriesFromCatalog() {
    const source  = readFileSync( join( ROOT, 'src', 'js', 'icons.js' ), 'utf8' );
    const sandbox = {};

    new Function( 'window', source )( sandbox );

    return Object.keys( sandbox.abakusIconPicker.icons );
}

/** Title-cases a catalog key the way the plug-in does when no message exists. */
function englishLabel( category ) {
    if ( category === 'AI' ) {
        return 'AI';
    }
    return category
        .split( '_' )
        .map( word => word.charAt( 0 ) + word.slice( 1 ).toLowerCase() )
        .join( ' ' );
}

function sqlLiteral( value ) {
    return "'" + String( value ).replace( /'/g, "''" ) + "'";
}

function createMessage( name, text ) {
    return [
        '    apex_lang.create_message(',
        '        p_application_id     => l_application_id,',
        `        p_name               => ${ sqlLiteral( name ) },`,
        '        p_language           => l_language,',
        `        p_message_text       => ${ sqlLiteral( text ) },`,
        '        p_used_in_javascript => true );'
    ].join( '\n' );
}

// ---------------------------------------------------------------------------

const categories = categoriesFromCatalog();

const body = [
    '-- User interface',
    UI_MESSAGES.map( ( [ name, text, note ] ) =>
        `    -- ${ note }\n${ createMessage( name, text ) }` ).join( '\n\n' ),
    '',
    '    -- Category tab and heading names',
    categories.map( category => createMessage( 'IP.CATEGORY.' + category, englishLabel( category ) ) ).join( '\n\n' ),
    '',
    '    -- OTHER is added at run time when the instance has icons this build does not know',
    createMessage( 'IP.CATEGORY.OTHER', 'Other' )
].join( '\n' );

const sql = `--------------------------------------------------------------------------------
-- Icon Picker - translatable Text Messages
-- https://github.com/grlicaa/IconPicker
--
-- Generated by tools/gen-messages.mjs from src/js/icons.js. Do not edit by hand; to change
-- the wording, translate a copy of this file.
--
-- Every message is created with p_used_in_javascript => true, which is what puts it within
-- reach of the apex.lang API the plug-in uses. Without that flag the message exists but the
-- picker cannot see it.
--
-- To use:
--   1. set l_application_id below to your application id
--   2. run it against the parsing schema of your application
--
-- To translate:
--   1. copy this file, e.g. IP_messages_de.sql
--   2. change l_language to the IANA code of your language, e.g. 'de'
--   3. translate the message texts, leaving the %0 placeholders in place
--   4. run it the same way
--
-- Creating none of these is perfectly fine. Any message that does not exist falls back to
-- the English text built into the plug-in.
--------------------------------------------------------------------------------
declare
    l_application_id constant number       := 100;    -- <== set your application id
    l_language       constant varchar2(10) := 'en';
begin

${ body }

    commit;
end;
/
`;

mkdirSync( dirname( TARGET ), { recursive: true } );
writeFileSync( TARGET, sql );

console.log( `Wrote docs/text-messages/IP_messages_en.sql` );
console.log( `  interface messages : ${ UI_MESSAGES.length }` );
console.log( `  category messages  : ${ categories.length } + OTHER` );
