/*
 * gen-icons.mjs
 *
 * Builds src/js/icons.js from the Font APEX catalog harvested off the Universal Theme
 * sample app (tools/apexIcons-2.5.1.json).
 *
 * The catalog is harvested with the Playwright MCP, not curl - oracleapex.com and
 * static.oracle.com are not reachable over plain HTTP from a build machine behind the
 * usual corporate egress rules:
 *
 *   browser_navigate  https://oracleapex.com/ords/r/apex_pm/ut/icons
 *   browser_evaluate  () => JSON.stringify( window.apexIcons )
 *
 * Any icon that v2.0 shipped but 2.5.1 dropped is kept in a trailing LEGACY category so
 * values already stored in customer tables still render, and can still be re-picked.
 *
 *   node tools/gen-icons.mjs
 */

import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const ROOT = join( dirname( fileURLToPath( import.meta.url ) ), '..' );

const FONT_APEX_VERSION = '2.5.1';
const SOURCE_JSON       = join( ROOT, 'tools', 'apexIcons-2.5.1.json' );
const LEGACY_JS         = join( ROOT, 'docs', 'js', 'IPicons.js' );
const TARGET_JS         = join( ROOT, 'src', 'js', 'icons.js' );

// ---------------------------------------------------------------------------
// read the harvested 2.5.1 catalog
// ---------------------------------------------------------------------------

function readCatalog( path ) {
    let data = JSON.parse( readFileSync( path, 'utf8' ) );

    // browser_evaluate returns a string, which the MCP then JSON-encodes again
    if ( typeof data === 'string' ) {
        data = JSON.parse( data );
    }
    return data;
}

// ---------------------------------------------------------------------------
// read the v2.0 catalog so we can spot icons Oracle has since removed
// ---------------------------------------------------------------------------

function readV2Catalog( path ) {
    if ( !existsSync( path ) ) {
        return null;                        // 2.0's catalog is gone from the tree
    }

    const source  = readFileSync( path, 'utf8' );
    const sandbox = {};

    // docs/js/IPicons.js is a plain assignment to `fontapex.icons`, no side effects
    new Function( 'globalThis', `var window = globalThis; ${ source }; globalThis.result = fontapex.icons;` )( sandbox );

    return sandbox.result;
}

// ---------------------------------------------------------------------------
// serialise - one icon per line so `git diff` on a future Font APEX bump is readable
// ---------------------------------------------------------------------------

function serialise( catalog ) {
    const categories = Object.keys( catalog ).map( category => {
        const entries = catalog[ category ]
            .map( icon => '        ' + JSON.stringify( icon ) )
            .join( ',\n' );

        return `    ${ JSON.stringify( category ) }: [\n${ entries }\n    ]`;
    } );

    return `{\n${ categories.join( ',\n' ) }\n}`;
}

// ---------------------------------------------------------------------------

const current = readCatalog( SOURCE_JSON );
const v2      = readV2Catalog( LEGACY_JS );

const currentNames = new Set( Object.values( current ).flat().map( icon => icon.name ) );
const v2Names      = new Map();

for ( const icons of Object.values( v2 || {} ) ) {
    for ( const icon of icons ) {
        // v2.0 has at least one name with a stray trailing space ("fa-clipboard-chart ")
        const name = icon.name.trim();

        if ( !v2Names.has( name ) ) {
            v2Names.set( name, { ...icon, name } );
        }
    }
}

const retired = [ ...v2Names.keys() ]
    .filter( name => !currentNames.has( name ) )
    .sort()
    .map( name => v2Names.get( name ) );

const catalog = { ...current };

if ( retired.length ) {
    catalog.LEGACY = retired;
}

const total  = Object.values( catalog ).reduce( ( sum, icons ) => sum + icons.length, 0 );
const unique = new Set( Object.values( catalog ).flat().map( icon => icon.name ) ).size;

const output = `/*!
 * Icon Picker - Font APEX ${ FONT_APEX_VERSION } icon catalog
 *
 * Generated by tools/gen-icons.mjs. Do not edit by hand.
 *
 * ${ Object.keys( catalog ).length } categories, ${ total } entries, ${ unique } unique icons.
${ retired.length
    ? ' * The LEGACY category holds icons that shipped with Icon Picker 2.0 but were removed from\n'
      + ' * Font APEX, so values already stored in application tables stay selectable.'
    : ' * Every icon that shipped with Icon Picker 2.0 still exists in this release, so no stored\n'
      + ' * value is orphaned by the upgrade.' }
 */
( function ( global ) {
    "use strict";

    var ip = global.abakusIconPicker = global.abakusIconPicker || {};

    ip.fontApexVersion = ${ JSON.stringify( FONT_APEX_VERSION ) };

    ip.icons = ${ serialise( catalog ) };

} )( window );
`;

writeFileSync( TARGET_JS, output );

console.log( `Font APEX ${ FONT_APEX_VERSION }` );
console.log( `  categories : ${ Object.keys( catalog ).length }` );
console.log( `  entries    : ${ total }` );
console.log( `  unique     : ${ unique }` );
console.log( v2
    ? `  retired    : ${ retired.length } icon(s) moved to LEGACY`
    : `  retired    : not checked, ${ LEGACY_JS } is not in the tree`
      + ' (restore it with: git show master:docs/js/IPicons.js > docs/js/IPicons.js)' );

if ( retired.length ) {
    console.log( '  ' + retired.map( icon => icon.name ).join( ', ' ) );
}
